def main():
    today = dict(DEFAULT_TODAY)
    if '--json' in sys.argv:
        i = sys.argv.index('--json')
        with open(sys.argv[i + 1], 'r', encoding='utf-8') as f:
            today = json.load(f)
    e, s = emotion_index(today)
    print('=' * 56)
    print('A股情绪指数计算  |  %s' % today['date'])
    print('=' * 56)
    print('情绪指数: %.1f / 100   档位: %s' % (e, level(e)))
    print('-' * 56)
    for k in WEIGHTS:
        print('  %-8s 权重%.0f%%  归一得分 %.2f' % (k, WEIGHTS[k] * 100, s[k]))
    print('-' * 56)
    for a in alert(e, today):
        print('[预警]', a)
    print('=' * 56)
    print('历史冰点校准(验证: 冰点样本应落在30以下):')
    for h in HIST_SAMPLES:
        he, _ = emotion_index(h)
        flag = 'OK' if he <= 30 else 'FAIL'
        print('  %-20s 情绪指数 %6.1f  %s' % (h['date'], he, flag))

if __name__ == '__main__':
    main()
